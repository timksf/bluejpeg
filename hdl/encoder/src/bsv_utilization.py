#!/usr/bin/env python3
"""
Parse BSV source files to extract the module instantiation hierarchy,
then generate a Vivado TCL script that reports per-module utilization
by grouping flat cells by their BSC-generated name prefixes.

Usage:
    python3 bsv_utilization.py <bsv_src_dir> <top_constructor> [--out <output.tcl>]

Example:
    python3 bsv_utilization.py src/ mkBlueJPEG --out util_modules.tcl
"""

import argparse
import re
import sys
from pathlib import Path
from collections import defaultdict

# BSV/library primitives to skip (these are not "design modules")
PRIMITIVE_CONSTRUCTORS = {
    # Registers
    "mkReg", "mkRegU", "mkRegA", "mkCReg", "mkConfigReg", "mkConfigRegU",
    # FIFOs
    "mkFIFO", "mkFIFO1", "mkFIFOF", "mkFIFO1F", "mkFIFOF1",
    "mkSizedFIFO", "mkSizedFIFOF",
    "mkPipelineFIFO", "mkPipelineFIFOF",
    "mkBypassFIFO", "mkBypassFIFOF",
    "mkLFIFO", "mkLFIFOF",
    "mkUGFIFO", "mkUGFIFOF", "mkUGSizedFIFO", "mkUGSizedFIFOF",
    # BRAMs
    "mkBRAM1Server", "mkBRAM1ServerBE", "mkBRAM2Server", "mkBRAMCore1",
    # RegFiles
    "mkRegFile", "mkRegFileFull", "mkRegFileWCF",
    # Wires
    "mkWire", "mkRWire", "mkDWire", "mkPulseWire", "mkBypassWire",
    # Gearbox
    "mk1toNGearbox", "mkNto1Gearbox",
    # Reset
    "mkReset", "mkResetSync", "mkAsyncReset", "mkAsyncResetFromCR",
    # Connectable / misc
    "mkConnection", "mkSyncFIFO", "mkSyncFIFOFromCC", "mkSyncFIFOToCC",
    "mkSyncReg", "mkNullCrossingReg", "mkNullCrossingWire",
    # AXI library (treat as primitives for hierarchy purposes)
    "mkAXI4_Stream_Rd", "mkAXI4_Stream_Wr",
    "mkAXI4_Lite_Master", "mkAXI4_Lite_Slave",
    # Config
    "axi4LiteConfigFromContext",
    # Misc library
    "replicateM",
}

# Pattern: identifier <- mkConstructor or identifier <- mkConstructor(args)
# Also handles: let identifier <- mkConstructor
INST_PATTERN = re.compile(
    r'(?:let\s+)?(\w+)\s*<-\s*(mk\w+|axi4\w+)',
    re.IGNORECASE
)

# Module definition: module mkFoo or module [ctx] mkFoo
MODULE_DEF_PATTERN = re.compile(
    r'module\s+(?:\[.*?\]\s+)?(mk\w+)',
)


def parse_bsv_file(filepath):
    """Parse a BSV file and return (module_name, [(inst_name, constructor), ...])
    for each module defined in the file."""
    text = filepath.read_text(errors='replace')

    modules = {}  # constructor_name -> [(inst_name, sub_constructor)]
    current_module = None

    for line in text.splitlines():
        # Strip comments
        line = re.sub(r'//.*', '', line)

        mod_match = MODULE_DEF_PATTERN.search(line)
        if mod_match:
            current_module = mod_match.group(1)
            modules[current_module] = []
            continue

        if current_module:
            inst_match = INST_PATTERN.search(line)
            if inst_match:
                inst_name = inst_match.group(1)
                constructor = inst_match.group(2)
                modules[current_module].append((inst_name, constructor))

    return modules


def build_module_db(src_dir):
    """Scan all BSV files and build a database of constructor -> instantiations."""
    db = {}  # constructor_name -> [(inst_name, sub_constructor)]
    src_path = Path(src_dir)

    for bsv_file in sorted(src_path.glob("*.bsv")):
        modules = parse_bsv_file(bsv_file)
        for name, insts in modules.items():
            if name in db:
                # Module defined in multiple files (unlikely) — merge
                db[name].extend(insts)
            else:
                db[name] = insts

    return db


def resolve_hierarchy(db, constructor, prefix="", depth=0, max_depth=10):
    """Recursively resolve the module instantiation tree.
    Returns a list of (vivado_prefix, constructor_name, depth) tuples
    representing the design modules (non-primitives) in the hierarchy."""

    if depth > max_depth:
        return []

    if constructor not in db:
        return []

    results = []
    for inst_name, sub_constructor in db[constructor]:
        if sub_constructor in PRIMITIVE_CONSTRUCTORS:
            continue

        # Compute the Vivado cell name prefix
        # BSC joins instance names with '_'
        if prefix:
            child_prefix = f"{prefix}_{inst_name}"
        else:
            child_prefix = inst_name

        results.append((child_prefix, sub_constructor, depth))

        # Recurse into sub-module if it's defined in our project
        sub_results = resolve_hierarchy(db, sub_constructor, child_prefix, depth + 1, max_depth)
        results.extend(sub_results)

    return results


def generate_tcl(hierarchy, top_module, sections, outfile=None):
    """Generate Vivado TCL to report per-module utilization."""

    lines = []
    lines.append(f'# Auto-generated BSV module utilization analysis for {top_module}')
    lines.append(f'# Generated by bsv_utilization.py')
    lines.append('')

    # Section filter: extract only matching sections from report_utilization output.
    # Vivado sections are delimited by lines starting with "+---" (table borders)
    # and section headers like "1. CLB Logic", "2. BLOCKRAM", etc.
    lines.append('# Filter a report_utilization string to keep only specified sections.')
    lines.append('# section_patterns: list of glob patterns to match against section headers')
    lines.append('# e.g. {"CLB Logic" "Primitives" "BLOCKRAM"}')
    lines.append('proc filter_util_sections {rpt section_patterns} {')
    lines.append('    set result {}')
    lines.append('    set in_section 0')
    lines.append('    set capture 0')
    lines.append('    set section_lines {}')
    lines.append('    foreach line [split $rpt "\\n"] {')
    lines.append('        # Detect section header: e.g. "1. CLB Logic" or "1.1 Summary of Registers"')
    lines.append('        if {[regexp {^\\d+\\.\\d*\\s+(.+)$} $line -> sec_name]} {')
    lines.append('            # Flush previous section if captured')
    lines.append('            if {$capture && [llength $section_lines] > 0} {')
    lines.append('                append result [join $section_lines "\\n"]')
    lines.append('                append result "\\n"')
    lines.append('            }')
    lines.append('            set section_lines {}')
    lines.append('            set capture 0')
    lines.append('            set sec_name [string trim $sec_name]')
    lines.append('            foreach pat $section_patterns {')
    lines.append('                if {[string match -nocase "*${pat}*" $sec_name]} {')
    lines.append('                    set capture 1')
    lines.append('                    break')
    lines.append('                }')
    lines.append('            }')
    lines.append('        }')
    lines.append('        if {$capture} {')
    lines.append('            lappend section_lines $line')
    lines.append('        }')
    lines.append('    }')
    lines.append('    # Flush last section')
    lines.append('    if {$capture && [llength $section_lines] > 0} {')
    lines.append('        append result [join $section_lines "\\n"]')
    lines.append('        append result "\\n"')
    lines.append('    }')
    lines.append('    return $result')
    lines.append('}')
    lines.append('')

    # Build the section filter list for TCL
    if sections:
        tcl_sections = " ".join(f'"{s}"' for s in sections)
        filter_expr = f'[list {tcl_sections}]'
    else:
        filter_expr = None

    lines.append('proc report_bsv_hierarchy {outfile} {')
    lines.append('    set fp [open $outfile w]')
    lines.append(f'    puts $fp "============================================================"')
    lines.append(f'    puts $fp "  BSV Module Utilization Report"')
    lines.append(f'    puts $fp "  Top module: {top_module}"')
    if sections:
        lines.append(f'    puts $fp "  Sections: {", ".join(sections)}"')
    lines.append(f'    puts $fp "============================================================"')
    lines.append(f'    puts $fp ""')
    lines.append('')

    # Group by depth for nice indented output
    for prefix, constructor, depth in hierarchy:
        indent = "  " * depth
        label = f"{indent}{prefix} ({constructor})"
        tcl_label = label.replace('"', '\\"')

        lines.append(f'    # {label}')
        lines.append(f'    set cells [get_cells -quiet {prefix}_*]')
        lines.append(f'    set n [llength $cells]')
        lines.append(f'    if {{$n > 0}} {{')
        lines.append(f'        puts $fp "\\n--- {tcl_label} --- ($n cells)"')
        lines.append(f'        set rpt [report_utilization -cells $cells -return_string]')
        if filter_expr:
            lines.append(f'        set rpt [filter_util_sections $rpt {filter_expr}]')
        lines.append(f'        puts $fp $rpt')
        lines.append(f'    }} else {{')
        lines.append(f'        puts $fp "\\n--- {tcl_label} --- (0 cells, possibly fully optimized)"')
        lines.append(f'    }}')
        lines.append('')

    # Report uncategorized cells (top-level logic not belonging to any submodule)
    lines.append('    # --- Uncategorized (top-level glue logic) ---')
    lines.append('    set all_top_cells [get_cells -quiet *]')
    lines.append('    set categorized {}')
    for prefix, _, depth in hierarchy:
        if depth == 0:
            lines.append(f'    set categorized [concat $categorized [get_cells -quiet {prefix}_*]]')
    lines.append('    set n_total [llength $all_top_cells]')
    lines.append('    set n_cat [llength $categorized]')
    lines.append('    puts $fp "\\n============================================================"')
    lines.append('    puts $fp "  Summary: $n_total total cells, $n_cat categorized"')
    lines.append('    puts $fp "============================================================"')
    lines.append('')
    lines.append('    close $fp')
    lines.append('    puts "BSV hierarchy utilization report written to $outfile"')
    lines.append('}')
    lines.append('')

    # Also generate a quick summary proc
    lines.append('proc report_bsv_summary {} {')
    lines.append(f'    puts "\\n=== BSV Module Utilization Summary ({top_module}) ==="')
    lines.append('    puts [format "%-50s %8s" "Module" "Cells"]')
    lines.append('    puts [string repeat "-" 60]')
    for prefix, constructor, depth in hierarchy:
        indent = ".." * depth
        label = f"{indent}{prefix} ({constructor})"
        lines.append(f'    set n [llength [get_cells -quiet {prefix}_*]]')
        lines.append(f'    puts [format "%-50s %8d" "{label}" $n]')
    lines.append('    puts [string repeat "-" 60]')
    lines.append('    puts [format "%-50s %8d" "TOTAL" [llength [get_cells -quiet *]]]')
    lines.append('}')

    output = '\n'.join(lines) + '\n'

    if outfile:
        Path(outfile).write_text(output)
        print(f"Written to {outfile}")
    else:
        print(output)


def print_hierarchy(hierarchy):
    """Print the parsed hierarchy tree for debugging."""
    print("\nParsed BSV module hierarchy:")
    print("=" * 60)
    for prefix, constructor, depth in hierarchy:
        indent = "  " * depth
        print(f"{indent}{prefix} <- {constructor}")
    print("=" * 60)


def main():
    parser = argparse.ArgumentParser(description="BSV module hierarchy → Vivado TCL utilization report")
    parser.add_argument("src_dir", help="Directory containing BSV source files")
    parser.add_argument("top", help="Top-level module constructor (e.g., mkBlueJPEG)")
    parser.add_argument("--out", "-o", help="Output TCL file (default: stdout)")
    parser.add_argument("--sections", "-s", nargs="*",
                        help="Only include these report_utilization sections (substring match). "
                             "E.g.: --sections 'CLB Logic' 'Primitives'")
    parser.add_argument("--tree", action="store_true", help="Print the hierarchy tree and exit")
    args = parser.parse_args()

    db = build_module_db(args.src_dir)

    if args.top not in db:
        print(f"Error: constructor '{args.top}' not found in BSV sources.", file=sys.stderr)
        print(f"Available constructors: {', '.join(sorted(db.keys()))}", file=sys.stderr)
        sys.exit(1)

    hierarchy = resolve_hierarchy(db, args.top)

    if not hierarchy:
        print(f"Warning: no non-primitive submodules found in '{args.top}'.", file=sys.stderr)

    print_hierarchy(hierarchy)

    if args.tree:
        return

    generate_tcl(hierarchy, args.top, args.sections or [], args.out)


if __name__ == "__main__":
    main()
